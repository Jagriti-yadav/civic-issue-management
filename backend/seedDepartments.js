import mongoose from 'mongoose';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import Department from './models/Department.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

dotenv.config({ path: path.join(__dirname, '.env') });

const seedDepartments = async () => {
  try {
    await mongoose.connect(process.env.MONGO_URI || 'mongodb://localhost:27017/smartcivic');
    console.log('Connected to MongoDB');

    // Clear existing departments
    await Department.deleteMany({});
    console.log('Cleared existing departments');

    const departments = [
      { name: 'Public Works', description: 'Responsible for roads, infrastructure, and public facilities' },
      { name: 'Water Department', description: 'Manages water supply and sanitation services' },
      { name: 'Electricity Board', description: 'Handles electricity distribution and maintenance' },
      { name: 'Sanitation Department', description: 'Waste management and cleanliness services' },
      { name: 'Police Department', description: 'Law enforcement and public safety' },
      { name: 'General Administration', description: 'Administrative services and general inquiries' }
    ];

    // Note: departmentId is auto-generated by the pre-save hook, so we need to create individually
    for (const deptData of departments) {
      const dept = await Department.create(deptData);
      console.log(`Created department: ${dept.name} (${dept.departmentId})`);
    }

    console.log('\n=== Departments Seeded ===');
    console.log('Total departments:', departments.length);
    console.log('========================\n');

    await mongoose.disconnect();
    console.log('Disconnected from MongoDB');
  } catch (error) {
    console.error('Error:', error.message);
    process.exit(1);
  }
};

seedDepartments();
